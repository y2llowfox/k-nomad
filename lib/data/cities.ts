function makeMetrics(
  scores: Record<string, number>,
): MetricScore[] {
  return METRICS.map((m) => ({
    key: m.key,
    label: m.label,
    emoji: m.emoji,
    score: scores[m.key] ?? 3.0,
  }));
}

function makeCosts(
  rent: number,
  food: number,
  transport: number,
  cafe: number,
  utility: number,
): CostItem[] {
  return [
    { category: "원룸 월세", amount: rent, unit: "만원/월" },
    { category: "식비", amount: food, unit: "만원/월" },
    { category: "교통비", amount: transport, unit: "만원/월" },
    { category: "카페", amount: cafe, unit: "만원/월" },
    { category: "유틸리티", amount: utility, unit: "만원/월" },
  ];
}

function makeWeather(
  temps: number[],
  rain: number[],
  humidity: number[],
): MonthlyWeather[] {
  return temps.map((t, i) => ({
    month: i + 1,
    avgTemp: t,
    rainfall: rain[i],
    humidity: humidity[i],
  }));
}

function pro(id: string, text: string, emoji: string, votes: number): ProConTag {
  return { id, text, emoji, type: "pro", votes };
}

function con(id: string, text: string, emoji: string, votes: number): ProConTag {
  return { id, text, emoji, type: "con", votes };
}

function makeCity(opts: {
  slug: string;
  name: string;
  nameEn: string;
  region: Region;
  category: City["category"];
  description: string;
  overallScore: number;
  reviewCount: number;
  metricScores: Record<string, number>;
  rent: number;
  food: number;
  transport: number;
  cafe: number;
  utility: number;
  monthlyCost: number;
  internetSpeed: number;
  currentTemp: number;
  weatherIcon: string;
  hasKTX: boolean;
  isSeaside: boolean;
  highlights: string[];
  pros: ProConTag[];
  cons: ProConTag[];
  temps: number[];
  rain: number[];
  humidity: number[];
  nearbySlugs: string[];
}): City {
  return {
    slug: opts.slug,
    name: opts.name,
    nameEn: opts.nameEn,
    region: opts.region,
    category: opts.category,
    description: opts.description,
    imageUrl: `https://picsum.photos/seed/${opts.slug}/800/500`,
    overallScore: opts.overallScore,
    reviewCount: opts.reviewCount,
    metrics: makeMetrics(opts.metricScores),
    costs: makeCosts(opts.rent, opts.food, opts.transport, opts.cafe, opts.utility),
    monthlyCost: opts.monthlyCost,
    internetSpeed: opts.internetSpeed,
    currentTemp: opts.currentTemp,
    weatherIcon: opts.weatherIcon,
    hasKTX: opts.hasKTX,
    isSeaside: opts.isSeaside,
    highlights: opts.highlights,
    pros: opts.pros,
    cons: opts.cons,
    weather: makeWeather(opts.temps, opts.rain, opts.humidity),
    nearbySlugs: opts.nearbySlugs,
    photos: [
      `https://picsum.photos/seed/${opts.slug}-1/800/500`,
      `https://picsum.photos/seed/${opts.slug}-2/800/500`,
      `https://picsum.photos/seed/${opts.slug}-3/800/500`,
    ],
  };
}

